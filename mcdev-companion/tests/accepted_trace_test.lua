local trace = dofile('mcdev-companion/tests/support/accepted_trace.lua')
local path = vim.fn.tempname()
local state = trace.start(path, 'mcdev.mixin')
local owner, sha = '/fixture/Owner.kt', string.rep('a', 64)
local expected = { [trace.owner_key(owner)] = sha }
local function append(text)
  local file = assert(io.open(path, 'ab'))
  file:write(text)
  file:close()
end
local function event(provider, digest, evaluation, instance, event_owner)
  return vim.json.encode({ name = 'extension.ipc.accepted', args = {
    provider = provider, owner = event_owner or owner, instance = instance or 7, evaluation = evaluation,
    publication_revision = 9, source_sha256 = digest,
  } })
end
local ok, failure = xpcall(function()
  append(event('unrelated', sha, '1') .. '\n')
  append(event('mcdev.mixin', string.rep('b', 64), '2') .. '\n')
  local floor = state:mark()
  assert(floor == 1)
  assert(not state:wait_for(expected, floor, 40))
  local json = event('mcdev.mixin', sha, '3')
  append(json:sub(1, 20))
  assert(state:mark() == floor)
  vim.defer_fn(function() append(json:sub(21) .. '\n') end, 20)
  local ready, found = state:wait_for(expected, floor, 1000)
  assert(ready and found[trace.owner_key(owner)].evaluation == '3')
  local next_floor = state:mark()
  assert(not state:wait_for(expected, next_floor, 40), 'old acceptance cannot satisfy a new boundary')
  append(event('mcdev.mixin', sha, '4', 7) .. '\n')
  state:mark()
  assert(not state:wait_for(expected, next_floor, 40, { fresh_instance = true }), 'old worker cannot satisfy re-enable')
  append(event('mcdev.mixin', sha, '5', 8) .. '\n')
  state:mark()
  local fresh, current = state:wait_for(expected, next_floor, 1000, { fresh_instance = true })
  assert(fresh and current[trace.owner_key(owner)].instance == 8)
  local group_floor = state:mark()
  local other = '/fixture/Other.java'
  local group_expected = { [trace.owner_key(owner)] = sha, [trace.owner_key(other)] = sha }
  append(event('mcdev.mixin', sha, '6', 9) .. '\n')
  append(event('mcdev.mixin', sha, '7', 10, other) .. '\n')
  state:mark()
  assert(not state:wait_for(group_expected, group_floor, 40, { fresh_instance = true }), 'mixed instances cannot form one accepted scope')
  append(event('mcdev.mixin', sha, '8', 9, other) .. '\n')
  state:mark()
  assert(state:wait_for(group_expected, group_floor, 1000, { fresh_instance = true }))
  local duplicate_floor = state:mark()
  append(event('mcdev.mixin', sha, '9', 11) .. '\n')
  append(event('mcdev.mixin', sha, '9', 11, other) .. '\n')
  state:mark()
  assert(not state:wait_for(group_expected, duplicate_floor, 40), 'one evaluation cannot name two owners')
  append(event('mcdev.mixin', sha, '10', 11, other) .. '\n')
  state:mark()
  assert(not state:wait_for(group_expected, duplicate_floor, 40, { required_instance = 99 }), 'foreign instance cannot satisfy unsaved scope')
  assert(state:wait_for(group_expected, duplicate_floor, 1000, { required_instance = 11 }))
  local replay_floor = state:mark()
  append(event('mcdev.mixin', sha, '9', 11) .. '\n')
  state:mark()
  assert(not state:wait_for(expected, replay_floor, 40), 'reused evaluation token cannot satisfy a new source boundary')
end, debug.traceback)
state:close()
vim.fn.delete(path)
assert(ok, failure)
print('accepted trace: PASS (provider/source scope, incremental records, freshness, filesystem events)')
vim.cmd('qa!')
